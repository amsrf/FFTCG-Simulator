#!/usr/bin/env python3
"""Build the keyword badges in assets/icons/keywords/ from game-icons.net glyphs.

Each source in assets/icons/keywords/source/ is a game-icons.net SVG (512x512, a black background square and a white
glyph). The background is dropped and the glyph is centred on the shared badge plate: a dark radial plate with a white
rim. One look for every badge, so a new keyword is one more entry in BADGES (plus a row in card_keyword_icons.gd).

game-icons.net art is CC BY 3.0: credit the author in assets/icons/keywords/CREDITS.md when adding one.

    python3 tools/build_keyword_icons.py
"""
import os
import re

ROOT = os.path.join(os.path.dirname(__file__), "..", "assets", "icons", "keywords")
SOURCE = os.path.join(ROOT, "source")
SIZE = 128
## The glyph's box inside the 128 plate: the inner rim sits at 11.5, so 18 px of margin keeps it clear of the border.
GLYPH_BOX = 92

# keyword badge name -> game-icons.net source file
BADGES = {
    "brave": "static-guard.svg",
    "first_strike": "bouncing-sword.svg",
    "indestructible": "stone-wall.svg",
    "cannot_block": "cracked-shield.svg",
}

PLATE = """<defs>
    <radialGradient id="plate" cx="50%" cy="42%" r="70%">
      <stop offset="0" stop-color="#2b2b2b"/>
      <stop offset="0.65" stop-color="#121212"/>
      <stop offset="1" stop-color="#050505"/>
    </radialGradient>
  </defs>
  <rect x="3" y="3" width="122" height="122" rx="24" fill="#000"/>
  <rect x="6" y="6" width="116" height="116" rx="21" fill="url(#plate)" stroke="#fff" stroke-width="3.5"/>
  <rect x="11.5" y="11.5" width="105" height="105" rx="16" fill="none" stroke="#fff" stroke-opacity="0.22" stroke-width="1.2"/>"""


def glyph(source_svg):
    """The source's drawing minus its full-canvas background square."""
    body = re.search(r"<svg[^>]*>(.*)</svg>", source_svg, re.S).group(1)
    body = re.sub(r'<path d="M0 0h512v512H0z"[^>]*>\s*</path>', "", body)
    body = re.sub(r'<path d="M0 0h512v512H0z"[^>]*/>', "", body)
    return body.strip()


def build(name, source_file):
    with open(os.path.join(SOURCE, source_file)) as f:
        src = f.read()
    offset = (SIZE - GLYPH_BOX) / 2
    scale = GLYPH_BOX / 512.0
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {s} {s}" width="{s}" height="{s}">\n'
           '  <!-- {name}: game-icons.net "{src}" (CC BY 3.0, see CREDITS.md) on the keyword plate.\n'
           '       Generated by tools/build_keyword_icons.py; edit the generator or the source, not this file. -->\n'
           '  {plate}\n'
           '  <g transform="translate({o:.2f} {o:.2f}) scale({k:.5f})">\n    {g}\n  </g>\n</svg>\n').format(
        s=SIZE, name=name, src=source_file[:-4], plate=PLATE, o=offset, k=scale, g=glyph(src))
    with open(os.path.join(ROOT, name + ".svg"), "w") as f:
        f.write(svg)


if __name__ == "__main__":
    for name, source_file in BADGES.items():
        build(name, source_file)
    print("wrote", sorted(BADGES))
